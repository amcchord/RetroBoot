#!/usr/bin/env python3
"""Build rbui's icon and cursor tables from assets/icons/*.icons.

The .icons files are the editable source of truth: original pixel art drawn
for RetroBoot, one character per pixel. This tool writes src/icons_data.c and,
with --preview, a PNG sheet showing every icon at 1x/2x/4x on the dialog gray,
on white and on the list selection colour.

Usage:
    icongen.py [--preview DIR] [--check]

Source format (UTF-8 text):

    # comment
    palette                 add or override palette letters (all files share
    K 000000                assets/icons/palette.txt first); RRGGBB is opaque,
    s 80000000              AARRGGBB blends (e.g. a soft shadow)
                            (blank line ends the block)
    icon disk 32            name and size; then exactly <size> rows of <size>
    ....KKKK....            characters. '.' and ' ' are transparent.
                            (blank line ends the block)
    icon cursor 16 hot=1,1  optional hot spot (cursor only)
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fontgen import write_png, Canvas  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
UI_DIR = os.path.dirname(HERE)
ICON_DIR = os.path.join(UI_DIR, 'assets', 'icons')

REQUIRED = ['mac', 'disk', 'cd', 'folder', 'network', 'wifi', 'web', 'wrench', 'stop', 'caution', 'note']


def parse_palette_lines(lines, start, pal, errors, path):
    i = start
    while i < len(lines) and lines[i].strip():
        parts = lines[i].split()
        if len(parts) != 2 or len(parts[0]) != 1 or len(parts[1]) not in (6, 8):
            errors.append('%s:%d: bad palette line %r' % (path, i + 1, lines[i]))
        else:
            v = int(parts[1], 16)
            if len(parts[1]) == 6:
                v |= 0xFF000000
            pal[parts[0]] = v
        i += 1
    return i


def load(paths):
    errors = []
    base = {}
    pal_path = os.path.join(ICON_DIR, 'palette.txt')
    with open(pal_path, encoding='utf-8') as f:
        lines = [l.rstrip('\n') for l in f if not l.startswith('#')]
    parse_palette_lines([l for l in lines if l.strip()], 0, base, errors, pal_path)
    icons = []
    for path in paths:
        pal = dict(base)
        with open(path, encoding='utf-8') as f:
            lines = [l.rstrip('\n') for l in f]
        i = 0
        while i < len(lines):
            line = lines[i]
            i += 1
            if not line.strip() or line.startswith('#'):
                continue
            parts = line.split()
            if parts[0] == 'palette':
                i = parse_palette_lines(lines, i, pal, errors, path)
            elif parts[0] == 'icon' and len(parts) >= 3:
                name, size = parts[1], int(parts[2])
                hot = (0, 0)
                for p in parts[3:]:
                    if p.startswith('hot='):
                        hot = tuple(int(v) for v in p[4:].split(','))
                rows = []
                while i < len(lines) and lines[i].strip():
                    rows.append(lines[i].rstrip())
                    i += 1
                if len(rows) != size or any(len(r) != size for r in rows):
                    errors.append('%s: icon %s: expected %dx%d art, got %d rows (widths %s)' % (
                        path, name, size, size, len(rows), sorted({len(r) for r in rows})))
                    continue
                px = []
                for r in rows:
                    for ch in r:
                        if ch in '. ':
                            px.append(0)
                        elif ch in pal:
                            px.append(pal[ch])
                        else:
                            errors.append('%s: icon %s: unknown palette letter %r' % (path, name, ch))
                            px.append(0)
                icons.append({'name': name, 'size': size, 'px': px, 'hot': hot, 'path': path})
            else:
                errors.append('%s:%d: unknown line %r' % (path, i, line))
    return icons, errors


def write_c(icons, out_path):
    out = ['/* Generated by tools/icongen.py from the .icons files in assets/icons. Do not edit.',
           ' * Icons and cursor: original RetroBoot pixel art, MIT License (assets/icons/LICENSE-icons.txt). */',
           '#include "icons.h"', '']
    table = []
    for ic in sorted(icons, key=lambda c: (c['name'], c['size'])):
        colors = sorted(set(ic['px']) - {0})
        index = {c: n + 1 for n, c in enumerate(colors)}
        ident = '%s_%d' % (ic['name'], ic['size'])
        out.append('static const uint32_t pal_%s[] = {0x00000000, %s};' % (
            ident, ', '.join('0x%08X' % c for c in colors)))
        out.append('static const uint8_t px_%s[] = {' % ident)
        s = ic['size']
        for y in range(s):
            out.append('    ' + ','.join('%d' % (index[v] if v else 0) for v in ic['px'][y * s:(y + 1) * s]) + ',')
        out.append('};')
        table.append('    {"%s", %d, %d, %d, pal_%s, px_%s, 0},' % (ic['name'], s, ic['hot'][0], ic['hot'][1], ident, ident))
    out.append('')
    out.append('const rbi_icon rbui_icons[] = {')
    out.extend(table)
    out.append('};')
    out.append('const int rbui_icon_count = %d;' % len(table))
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')


def blend(dst, argb):
    a = (argb >> 24) & 0xFF
    r, g, b = (argb >> 16) & 0xFF, (argb >> 8) & 0xFF, argb & 0xFF
    return tuple((s * a + d * (255 - a) + 127) // 255 for s, d in zip((r, g, b), dst))


def preview(icons, path):
    bgs = [(0xE6, 0xE6, 0xE6), (0xFF, 0xFF, 0xFF), (0xCC, 0xCC, 0xFF)]
    scales = [1, 2, 4]
    col_w = sum(32 * s + 8 for s in scales) * len(bgs) + 16
    by_name = {}
    for ic in icons:
        by_name.setdefault(ic['name'], []).append(ic)
    names = sorted(by_name)
    row_h = 32 * 4 + 12
    H = 8 + len(names) * (row_h * 2) + 8
    cv = Canvas(col_w, H, (0x80, 0x80, 0x80))
    y = 8
    for name in names:
        for ic in sorted(by_name[name], key=lambda c: -c['size']):
            x = 8
            for bg in bgs:
                cv.rect(x - 4, y - 4, sum(32 * s + 8 for s in scales), row_h, bg)
                for s in scales:
                    for py in range(ic['size']):
                        for px in range(ic['size']):
                            v = ic['px'][py * ic['size'] + px]
                            if v:
                                c = blend(bg, v)
                                cv.rect(x + px * s, y + py * s, s, s, c)
                    x += 32 * s + 8
                x += 0
            y += row_h
    write_png(path, cv.w, cv.h, cv.pix)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--preview', metavar='DIR')
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--c-out', default=os.path.join(UI_DIR, 'src', 'icons_data.c'))
    args = ap.parse_args()
    paths = sorted(os.path.join(ICON_DIR, f) for f in os.listdir(ICON_DIR) if f.endswith('.icons'))
    icons, errors = load(paths)
    have = {(ic['name'], ic['size']) for ic in icons}
    for name in REQUIRED:
        for size in (16, 32):
            if (name, size) not in have:
                errors.append('missing icon %s %d' % (name, size))
    if len(have) != len(icons):
        errors.append('duplicate icon name/size')
    if errors:
        print('\n'.join(errors), file=sys.stderr)
        if args.check or any(not e.startswith('missing') for e in errors):
            return 1
    if args.check:
        return 0
    write_c(icons, args.c_out)
    print('wrote %s (%d icons)' % (os.path.relpath(args.c_out), len(icons)))
    if args.preview:
        os.makedirs(args.preview, exist_ok=True)
        preview(icons, os.path.join(args.preview, 'icons.png'))
        print('wrote', os.path.join(args.preview, 'icons.png'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
