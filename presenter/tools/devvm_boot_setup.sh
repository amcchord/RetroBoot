#!/bin/sh
# Configure a Debian 13 development VM (rb-dev, VM 163) so its boot path
# matches what the appliance image must do around the presenter:
# GRUB draws the identical checkerboard and hides everything, the kernel keeps
# the firmware framebuffer untouched (no fbdev/fbcon), the initramfs splash
# redraws it on the KMS device, and rb-presenter takes over without a modeset.
# This is a lab reference for the image workstream, not a product installer.
#
#   devvm_boot_setup.sh [WxH]            (default 1280x800)
#   devvm_boot_setup.sh --revert
#   devvm_boot_setup.sh --pixel-scale auto|1-4 | --settings FILE [rb-bootdisplay options]
#       only redraw the GRUB background for display.pixel_scale and the startup
#       indicator (ARCHITECTURE 4.4.1) and pass retroboot.pixel_scale,
#       .progress, .guest_size, .checker_scale and .startup_ms to Linux, with
#       the image's own rb-bootdisplay (installed at /usr/lib/retroboot/image/)
#       on the recorded boot mode; the Platinum art's cpio becomes an early
#       initrd (GRUB_EARLY_INITRD_LINUX_CUSTOM). hostd's bootdisplay_cmd on
#       rb-dev (the image uses its ESP instead). Extra options (--timing FILE,
#       --art FILE) go to rb-bootdisplay.
set -eu
MODE=${1:-1280x800}
BIN=/usr/lib/retroboot/bin

if [ "$MODE" = "--pixel-scale" ] || [ "$MODE" = "--settings" ]; then
    esp=/var/lib/retroboot-devvm/esp
    mkdir -p "$esp"
    /usr/lib/retroboot/image/rb-bootdisplay --esp "$esp" "$@"
    cfg="$esp/grub/retroboot/display.cfg"
    val() { sed -n "s|^set $1=||p" "$cfg"; }
    png=$(val rb_checker | sed 's|^/grub/retroboot/||')
    cp "$esp/grub/retroboot/$png" /boot/grub/rb-checker.png.new
    mv /boot/grub/rb-checker.png.new /boot/grub/rb-checker.png
    args="retroboot.progress=$(val rb_progress) retroboot.guest_size=$(val rb_guest_size)"
    args="$args retroboot.checker_scale=$(val rb_checker_scale) retroboot.startup_ms=$(val rb_startup_ms)"
    args="$args retroboot.pixel_scale=$(val rb_pixel_scale) retroboot.rotation=$(val rb_rotation | grep . || echo 0)"
    f=/etc/default/grub.d/retroboot.cfg
    sed -i -e 's/ retroboot\.[a-z_]*=[^ "]*//g' -e "s/^\(GRUB_CMDLINE_LINUX_DEFAULT=\".*\)\"\$/\1 $args\"/" \
        -e '/^GRUB_EARLY_INITRD_LINUX_CUSTOM=/d' "$f"
    initrd=$(val rb_startup_initrd | sed 's|^/grub/retroboot/||')
    rm -f /boot/rb-startup.cpio
    if [ -n "$initrd" ]; then
        cp "$esp/grub/retroboot/$initrd" /boot/rb-startup.cpio
        echo 'GRUB_EARLY_INITRD_LINUX_CUSTOM="rb-startup.cpio"' >> "$f"
    fi
    update-grub 2>/dev/null
    sync
    echo "background $png; $args${initrd:+; art initrd $initrd}"
    exit 0
fi

if [ "$MODE" = "--revert" ]; then
    rm -f /etc/default/grub.d/retroboot.cfg /etc/grub.d/01_retroboot_background
    sed -i 's/^quiet_boot="1"/quiet_boot="0"/' /etc/grub.d/10_linux
    systemctl disable retroboot-presenter.service || true
    systemctl unmask getty@tty1.service ctrl-alt-del.target || true
    rm -f /etc/systemd/logind.conf.d/retroboot.conf /etc/systemd/system.conf.d/retroboot.conf
    update-initramfs -u
    update-grub
    exit 0
fi

W=${MODE%x*}
H=${MODE#*x}

# 1. GRUB background: generated by the presenter's own pattern code so GRUB,
#    the splash and the presenter produce bit-identical framebuffers.
"$BIN/rb-presenter" --write-checkerboard "$W" "$H" 0 /boot/grub/rb-checker.png

mkdir -p /etc/default/grub.d
cat > /etc/default/grub.d/retroboot.cfg <<EOF
GRUB_TIMEOUT=0
GRUB_TIMEOUT_STYLE=hidden
GRUB_TERMINAL_OUTPUT="gfxterm serial"
GRUB_GFXMODE=${W}x${H}x32
GRUB_GFXPAYLOAD_LINUX=keep
GRUB_CMDLINE_LINUX="console=ttyS0,115200"
GRUB_CMDLINE_LINUX_DEFAULT="quiet loglevel=0 rd.udev.log_level=0 udev.log_level=0 systemd.show_status=false rd.systemd.show_status=false vt.global_cursor_default=0 video=vesafb:off video=efifb:off drm_kms_helper.fbdev_emulation=0"
EOF

# Debian's 00_header forces "background_image -m stretch"; draw it 1:1.
cat > /etc/grub.d/01_retroboot_background <<'EOF'
#!/bin/sh
cat <<'GRUBEOF'
insmod png
background_image -m normal /boot/grub/rb-checker.png
GRUBEOF
EOF
chmod +x /etc/grub.d/01_retroboot_background
# No "Loading Linux ..." / "Loading initial ramdisk ..." echoes.
sed -i 's/^quiet_boot="0"/quiet_boot="1"/' /etc/grub.d/10_linux

# 2. systemd: nothing else on tty1; power key and Ctrl-Alt-Del belong to hostd.
systemctl mask getty@tty1.service ctrl-alt-del.target
mkdir -p /etc/systemd/logind.conf.d /etc/systemd/system.conf.d
cat > /etc/systemd/logind.conf.d/retroboot.conf <<'EOF'
[Login]
HandlePowerKey=ignore
HandleSuspendKey=ignore
HandleHibernateKey=ignore
HandleLidSwitch=ignore
HandleLidSwitchExternalPower=ignore
HandleLidSwitchDocked=ignore
NAutoVTs=0
ReserveVT=0
EOF
cat > /etc/systemd/system.conf.d/retroboot.conf <<'EOF'
[Manager]
CtrlAltDelBurstAction=none
ShowStatus=no
EOF
systemctl daemon-reload
systemctl enable retroboot-presenter.service

# 3. initramfs splash + KMS modules; then GRUB.
update-initramfs -u
update-grub
echo "boot path configured for ${W}x${H}"
