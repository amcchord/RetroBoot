#!/usr/bin/env python3
"""Generate src/isplash_font.h: RetroBoot System 12 for the installer startup
screen's built-in art (ARCHITECTURE 4.4.2).

The initramfs splash links no rbui, so the public fallback of the installer
startup screen carries its own copy of the MIT RetroBoot System 12 glyphs it
needs (printable ASCII and the ellipsis), generated from
presenter/ui/assets/fonts/RetroBoot-System-12.bdf (original RetroBoot pixel
art, MIT, presenter/ui/assets/fonts/LICENSE-fonts.txt).

    python3 presenter/tools/isplash_fontgen.py      # rewrites presenter/src/isplash_font.h
"""
from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
BDF = HERE.parent / "ui" / "assets" / "fonts" / "RetroBoot-System-12.bdf"
OUT = HERE.parent / "src" / "isplash_font.h"
CODES = list(range(0x20, 0x7F)) + [0x2026]


def parse(path: Path) -> tuple[int, dict[int, tuple[int, int, int, int, int, list[int]]]]:
    glyphs, ascent = {}, 0
    cur = None
    for line in path.read_text().splitlines():
        f = line.split()
        if not f:
            continue
        if f[0] == "FONT_ASCENT":
            ascent = int(f[1])
        elif f[0] == "ENCODING":
            cur = {"code": int(f[1]), "rows": []}
        elif f[0] == "DWIDTH" and cur is not None:
            cur["adv"] = int(f[1])
        elif f[0] == "BBX" and cur is not None:
            cur["bbx"] = tuple(int(v) for v in f[1:5])
        elif f[0] == "BITMAP" and cur is not None:
            cur["bitmap"] = True
        elif f[0] == "ENDCHAR" and cur is not None:
            w, h, xo, yo = cur["bbx"]
            glyphs[cur["code"]] = (cur["adv"], w, h, xo, yo, cur["rows"])
            cur = None
        elif cur is not None and cur.get("bitmap"):
            cur["rows"].append(int(line.strip(), 16))
    return ascent, glyphs


def main() -> int:
    ascent, glyphs = parse(BDF)
    out = ["/* Generated by presenter/tools/isplash_fontgen.py from presenter/ui/assets/fonts/",
           " * RetroBoot-System-12.bdf. Do not edit. Original RetroBoot pixel art, MIT License",
           " * (presenter/ui/assets/fonts/LICENSE-fonts.txt): the installer startup screen's",
           " * built-in text (installer_splash.c). Rows are MSB first, one byte per row. */",
           "#pragma once",
           "#include <stdint.h>",
           "",
           "struct rb_isplash_glyph {",
           "    uint16_t code;",
           "    uint8_t adv, w, h;",
           "    int8_t xoff, yoff; /* BDF: left bearing; bottom row relative to the baseline */",
           "    uint8_t rows[16];",
           "};",
           "",
           f"#define RB_ISPLASH_FONT_ASCENT {ascent}",
           "static const struct rb_isplash_glyph rb_isplash_font[] = {"]
    for code in CODES:
        if code not in glyphs:
            continue
        adv, w, h, xo, yo, rows = glyphs[code]
        if w > 8 or h > 16:
            raise SystemExit(f"glyph {code:#x} is larger than the table allows")
        rows_c = ", ".join(f"0x{r:02X}" for r in rows) or "0"
        out.append(f"    {{0x{code:04X}, {adv}, {w}, {h}, {xo}, {yo}, {{{rows_c}}}}},")
    out += ["};", ""]
    OUT.write_text("\n".join(out))
    print(f"{OUT}: {sum(1 for c in CODES if c in glyphs)} glyphs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
