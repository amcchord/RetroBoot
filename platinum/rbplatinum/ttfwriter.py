"""Write bitmap strikes as TrueType fonts whose glyphs are unions of pixel squares.

At font-size = the strike's pixel size (in CSS px, times any integer zoom) each
Mac pixel is exactly one square of the outline, so browsers rasterize the text
crisply and pixel for pixel.  Anti-aliased strikes (Mac OS 9 font smoothing,
16 coverage levels) become COLR v0 layered glyphs: one layer per coverage
level, palette entry k-1 = the text color at alpha 17*k/255, which composites
exactly like QuickDraw's linear blend.  The base glyph (shown by renderers
without COLR support) is the unsmoothed strike when one is given.

Standard library only; tables: head hhea maxp OS/2 hmtx cmap loca glyf name post
(+ COLR CPAL).
"""
from __future__ import annotations

import struct
import os

from .bitfont import ALIASES, BitFont, mac_to_unicode

UNITS = 64   # font units per Mac pixel
LEVELS = 16  # smoothed coverage levels 1..16 (palette entries per palette)


def _contours(pixels: set[tuple[int, int]]) -> list[list[tuple[int, int]]]:
    """Boundary loops of a pixel set (x right, y down), counter-clockwise on screen
    (so clockwise once y is flipped up, as TrueType wants outer contours)."""
    edges: dict[tuple[int, int], list[tuple[int, int]]] = {}
    es = set()
    for (x, y) in pixels:
        for a, b in (((x + 1, y), (x, y)), ((x, y), (x, y + 1)), ((x, y + 1), (x + 1, y + 1)), ((x + 1, y + 1), (x + 1, y))):
            if (b, a) in es:
                es.remove((b, a))
            else:
                es.add((a, b))
    for a, b in es:
        edges.setdefault(a, []).append(b)
    loops = []
    while edges:
        start = next(iter(edges))
        loop = [start]
        cur = start
        prev_dir = None
        while True:
            outs = edges[cur]
            if len(outs) == 1:
                nxt = outs.pop()
            else:  # pinch point: keep the turn that separates diagonal neighbours (turn left on screen)
                def turn(b):
                    d = (b[0] - cur[0], b[1] - cur[1])
                    if prev_dir is None:
                        return 0
                    cross = prev_dir[0] * d[1] - prev_dir[1] * d[0]
                    return cross
                outs.sort(key=turn)
                nxt = outs.pop(0)
            if not outs:
                del edges[cur]
            prev_dir = (nxt[0] - cur[0], nxt[1] - cur[1])
            cur = nxt
            if cur == start:
                break
            loop.append(cur)
        # drop collinear points
        pts = []
        n = len(loop)
        for i in range(n):
            p0, p1, p2 = loop[i - 1], loop[i], loop[(i + 1) % n]
            if (p1[0] - p0[0]) * (p2[1] - p1[1]) - (p1[1] - p0[1]) * (p2[0] - p1[0]) != 0:
                pts.append(p1)
        loops.append(pts)
    return loops


def _glyf(loops, top: int, left: int) -> tuple[bytes, tuple[int, int, int, int]]:
    """Simple glyph from screen loops; top = glyph row 0's height above baseline (px)."""
    if not loops:
        return b"", (0, 0, 0, 0)
    pts = []
    ends = []
    for lp in loops:
        for (x, y) in lp:
            pts.append(((left + x) * UNITS, (top - y) * UNITS))
        ends.append(len(pts) - 1)
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    bbox = (min(xs), min(ys), max(xs), max(ys))
    out = struct.pack(">hhhhh", len(ends), *bbox)
    out += b"".join(struct.pack(">H", e) for e in ends)
    out += struct.pack(">H", 0)  # no instructions
    flags = b""
    coords_x = b""
    coords_y = b""
    px, py = 0, 0
    for (x, y) in pts:
        dx, dy = x - px, y - py
        flags += b"\x01"
        coords_x += struct.pack(">h", dx)
        coords_y += struct.pack(">h", dy)
        px, py = x, y
    out += flags + coords_x + coords_y
    if len(out) % 2:
        out += b"\0"
    return out, bbox


def _checksum(data: bytes) -> int:
    data += b"\0" * (-len(data) % 4)
    return sum(struct.unpack(f">{len(data) // 4}I", data)) & 0xFFFFFFFF


def _name_table(family: str, style: str, version: str) -> bytes:
    full = f"{family} {style}".strip()
    ps = full.replace(" ", "-")
    names = {0: "Generated by RetroBoot rbplatinum from the user's own Mac OS disk; not for redistribution.",
             1: family, 2: style, 3: f"rbplatinum:{ps}", 4: full, 5: f"Version {version}", 6: ps}
    recs, strings = [], b""
    for nid, s in names.items():
        raw = s.encode("utf-16-be")
        recs.append(struct.pack(">HHHHHH", 3, 1, 0x409, nid, len(raw), len(strings)))
        strings += raw
    return struct.pack(">HHH", 0, len(recs), 6 + 12 * len(recs)) + b"".join(recs) + strings


def _cmap(char_to_gid: dict[int, int]) -> bytes:
    codes = sorted(c for c in char_to_gid if c <= 0xFFFF)
    segs = []
    for c in codes:
        if segs and c == segs[-1][1] + 1 and char_to_gid[c] - c == char_to_gid[segs[-1][0]] - segs[-1][0]:
            segs[-1][1] = c
        else:
            segs.append([c, c])
    segs.append([0xFFFF, 0xFFFF])
    n = len(segs)
    ends = b"".join(struct.pack(">H", e) for _s, e in segs)
    starts = b"".join(struct.pack(">H", s) for s, _e in segs)
    deltas = b"".join(struct.pack(">H", ((char_to_gid.get(s, 0) - s) & 0xFFFF) if s != 0xFFFF else 1)
                      for s, _e in segs)
    offsets = b"\0\0" * n
    import math
    sr = 2 * (2 ** int(math.log2(n)))
    sub = struct.pack(">HHHHHHH", 4, 0, 0, 2 * n, sr, int(math.log2(sr // 2)), 2 * n - sr)
    sub += ends + b"\0\0" + starts + deltas + offsets
    sub = sub[:2] + struct.pack(">H", len(sub)) + sub[4:]
    return struct.pack(">HHHHI", 0, 1, 3, 1, 12) + sub


def mac_blend(bg: int, fg: int, level: int) -> int:
    """QuickDraw's smoothed-text blend of one 8-bit channel (measured on Mac OS 9.2.1):
    bg + (((fg - bg) * 17 * level) >> 8), the shift flooring; level 16 (every sample
    covered) is the text color itself."""
    if level >= 16:
        return fg
    return bg + (((fg - bg) * 17 * level) >> 8)


def blend_alphas(fg: int, bgs: tuple[int, ...], mac_fg: int | None = None, exact_full: bool = False) -> list[int]:
    """Per-level alphas (1..15) for a palette color fg so that a browser's 8-bit
    compositing over each background channel in bgs lands on mac_blend(bg, mac_fg, level)
    (least total error where no single alpha is exact).  exact_full: level 15 is the
    text color itself (push-button titles), not a blend."""
    mac_fg = fg if mac_fg is None else mac_fg
    out = []
    for k in range(1, 16):
        best = None
        for a in range(256):
            err = 0
            for bg in bgs:
                want = mac_fg if (exact_full and k == 15) else mac_blend(bg, mac_fg, k)
                err += abs((fg * a + bg * (255 - a) + 127) // 255 - want)
            cand = (err, abs(a - 17 * k), a)
            if best is None or cand < best:
                best = cand
        out.append(best[2])
    return out


def build(strike: BitFont, family: str, style: str = "Regular", base: BitFont | None = None,
          palettes: list | None = None, version: str = "1.0") -> bytes:
    """TrueType bytes for one strike.  palettes: text colors for CPAL (smooth strikes),
    each (r, g, b) or ((r, g, b), [15 alphas])."""
    size = strike.size
    upem = size * UNITS
    ascent = strike.ascent
    descent = strike.descent + strike.leading   # leading folded into the descent: line height = ascent + descent
    codes = sorted(strike.glyphs)
    order = [None, 0x20] + [c for c in codes if c != 0x20]     # .notdef, space first
    glyphs = []          # (bytes, bbox, advance, lsb)
    layers: dict[int, list[tuple[int, int]]] = {}   # base gid -> [(layer gid, palette index)]
    layer_glyphs = []

    def glyph_bytes(g, threshold=None, only_level=None):
        pix = set()
        for y, row in enumerate(g.rows):
            for x, v in enumerate(row):
                if (only_level is not None and v == only_level) or (only_level is None and v >= (threshold or 1)):
                    pix.add((x, y))
        return _glyf(_contours(pix), g.top, g.left)

    char_to_gid = {}
    for gid, code in enumerate(order):
        g = strike.glyphs.get(code) if code is not None else strike.missing
        if g is None and code is not None:
            g = None
        adv = (g.advance if g else (strike.missing.advance if strike.missing else size // 2)) * UNITS
        if g is None:
            glyphs.append((b"", (0, 0, 0, 0), adv))
            continue
        if strike.smooth:
            fb = base.glyphs.get(code) if (base and code is not None) else None
            data, bbox = glyph_bytes(fb) if fb else glyph_bytes(g, threshold=9)
            levels = sorted({v for row in g.rows for v in row if v})
            if code is not None and levels:
                layers[gid] = []
                for lv in levels:
                    layer_glyphs.append(glyph_bytes(g, only_level=lv) + (0,))
                    layers[gid].append((len(order) + len(layer_glyphs) - 1, lv - 1))
        else:
            data, bbox = glyph_bytes(g)
        glyphs.append((data, bbox, adv))
        if code is not None:
            u = mac_to_unicode(code)
            char_to_gid[u] = gid
            if code == 0xCA:   # Mac Roman non-breaking space also serves U+00A0
                char_to_gid.setdefault(0xA0, gid)
    for alias, target in ALIASES.items():
        if target in char_to_gid:
            char_to_gid.setdefault(alias, char_to_gid[target])
    all_glyphs = glyphs + [(d, b, 0) for (d, b, _z) in layer_glyphs]
    num = len(all_glyphs)
    glyf = b""
    loca = []
    for d, _b, _a in all_glyphs:
        loca.append(len(glyf))
        glyf += d
    loca.append(len(glyf))
    loca_t = b"".join(struct.pack(">I", o) for o in loca)
    bbs = [b for _d, b, _a in all_glyphs if b != (0, 0, 0, 0)]
    xmin = min(b[0] for b in bbs)
    ymin = min(b[1] for b in bbs)
    xmax = max(b[2] for b in bbs)
    ymax = max(b[3] for b in bbs)
    hmtx = b"".join(struct.pack(">Hh", a, (b[0] if b != (0, 0, 0, 0) else 0)) for _d, b, a in all_glyphs)
    # Fixed timestamps keep builds byte-reproducible (SOURCE_DATE_EPOCH overrides).
    now = int(os.environ.get("SOURCE_DATE_EPOCH", "1000000000")) + 2082844800
    head = struct.pack(">IIIIHHqqhhhhHHhhh", 0x00010000, 0x00010000, 0, 0x5F0F3CF5, 0x000B, upem, now, now,
                       xmin, ymin, xmax, ymax, 0, 8, 2, 1, 0)
    adv_max = max(a for _d, _b, a in all_glyphs)
    hhea = struct.pack(">IhhhHhhhhhhhhhhhH", 0x00010000, ascent * UNITS, -descent * UNITS, 0, adv_max,
                       min((b[0] for b in bbs), default=0), 0, xmax, 1, 0, 0, 0, 0, 0, 0, 0, num)
    maxp = struct.pack(">IHHHHHHHHHHHHHH", 0x00010000, num, 4096, 256, 0, 0, 2, 0, 0, 0, 0, 0, 0, 0, 0)
    win_asc = max(ymax, ascent * UNITS)
    win_desc = max(-ymin, descent * UNITS)
    os2 = struct.pack(">HhHHHhhhhhhhhhhh", 4, size * UNITS // 2, 700 if style == "Bold" else 400, 5, 0,
                      upem // 5, upem // 5, 0, upem // 5, upem // 5, upem // 5, 0, upem // 5, UNITS, UNITS * 3, 0)
    os2 += b"\0" * 10 + b"\0" * 16 + b"RBPT"
    fs_sel = (0x20 if style == "Bold" else 0x40) | 0x80   # USE_TYPO_METRICS
    os2 += struct.pack(">HHHhhhHH", fs_sel, 0x20, 0xFF, ascent * UNITS, -descent * UNITS, 0, win_asc, win_desc)
    os2 += struct.pack(">II", 1, 0) + struct.pack(">hhHHH", ascent * UNITS, ascent * UNITS, 0, 0x20, 0)
    post = struct.pack(">IIhhIIIII", 0x00030000, 0, -UNITS * 2, UNITS, 1, 0, 0, 0, 0)
    tables = {"head": head, "hhea": hhea, "maxp": maxp, "OS/2": os2, "hmtx": hmtx, "cmap": _cmap(char_to_gid),
              "loca": loca_t, "glyf": glyf, "name": _name_table(family, style, version), "post": post}
    if strike.smooth and layers:
        recs = b""
        lrecs = b""
        k = 0
        for gid in sorted(layers):
            recs += struct.pack(">HHH", gid, k, len(layers[gid]))
            for lg, pi in layers[gid]:
                lrecs += struct.pack(">HH", lg, pi)
                k += 1
        tables["COLR"] = struct.pack(">HHIIH", 0, len(layers), 14, 14 + len(recs), k) + recs + lrecs
        pals = palettes or [(0, 0, 0)]
        entries = b""
        for pal in pals:
            (r, g, b), alphas = (pal[0], pal[1]) if len(pal) == 2 and isinstance(pal[0], tuple) else (pal, None)
            for lv in range(1, LEVELS + 1):
                a = alphas[lv - 1] if alphas and lv <= len(alphas) else min(255, 17 * lv)
                rr, gg, bb = r, g, b
                if isinstance(a, tuple):      # per-level color override: ((r, g, b), alpha)
                    (rr, gg, bb), a = a
                entries += struct.pack(">BBBB", bb, gg, rr, a)
        idx = b"".join(struct.pack(">H", LEVELS * i) for i in range(len(pals)))
        tables["CPAL"] = struct.pack(">HHHHI", 0, LEVELS, len(pals), LEVELS * len(pals), 12 + len(idx)) + idx + entries
    return _assemble(tables)


def _assemble(tables: dict[str, bytes]) -> bytes:
    import math
    tags = sorted(tables)
    n = len(tags)
    es = 2 ** int(math.log2(n))
    header = struct.pack(">IHHHH", 0x00010000, n, es * 16, int(math.log2(es)), n * 16 - es * 16)
    offset = 12 + 16 * n
    dirs = b""
    body = b""
    for t in tags:
        d = tables[t]
        dirs += struct.pack(">4sIII", t.encode("latin-1"), _checksum(d), offset + len(body), len(d))
        body += d + b"\0" * (-len(d) % 4)
    font = bytearray(header + dirs + body)
    # head.checkSumAdjustment
    hoff = 12 + 16 * tags.index("head")
    head_off = struct.unpack(">I", font[hoff + 8:hoff + 12])[0]
    adj = (0xB1B0AFBA - _checksum(bytes(font))) & 0xFFFFFFFF
    font[head_off + 8:head_off + 12] = struct.pack(">I", adj)
    return bytes(font)
