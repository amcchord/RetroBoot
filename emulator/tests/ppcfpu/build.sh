#!/bin/sh
# Build fpconf.elf (needs powerpc-linux-gnu-gcc; the RetroBoot builder has it).
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
OUT=${1:-$HERE/out}
CC=${CC:-powerpc-linux-gnu-gcc}
mkdir -p "$OUT"
python3 "$HERE/gen_ops.py" "$OUT"
cp "$HERE/bench_names.txt" "$HERE/fpconf.py" "$OUT/"
FLAGS="-m32 -mcpu=7400 -maltivec -mabi=altivec -mhard-float -O2 -ffreestanding -fno-builtin -nostdlib -fno-pic -fno-pie -msdata=none -mno-relocatable -Wall -Wextra -Wno-unused-parameter -I$HERE"
$CC $FLAGS -c "$HERE/start.S" -o "$OUT/start.o"
$CC $FLAGS -c "$OUT/ops.S" -o "$OUT/ops.o"
# little-endian stubs: assemble, then reverse the bytes of every word
$CC $FLAGS -c "$OUT/ops_le_src.S" -o "$OUT/ops_le_src.o"
${CC%gcc}objcopy -O binary -j .text "$OUT/ops_le_src.o" "$OUT/ops_le.bin"
python3 - "$OUT/ops_le.bin" "$OUT/ops_le.S" <<'PY'
import struct, sys
raw = open(sys.argv[1], 'rb').read()
words = struct.unpack('>%dI' % (len(raw) // 4), raw)
lines = ['/* generated by build.sh: ops_le_src.S with every word byte-reversed */',
         '\t.text', '\t.balign 32', '\t.globl op_le_base', 'op_le_base:']
lines += ['\t.long 0x%08x' % struct.unpack('<I', struct.pack('>I', w))[0] for w in words]
open(sys.argv[2], 'w').write('\n'.join(lines) + '\n')
PY
$CC $FLAGS -c "$OUT/ops_le.S" -o "$OUT/ops_le.o"
$CC $FLAGS -c "$HERE/fpconf.c" -o "$OUT/fpconf.o"
$CC $FLAGS -c "$HERE/bench.S" -o "$OUT/bench.o"
$CC $FLAGS -c "$HERE/bench.c" -o "$OUT/benchc.o"
$CC $FLAGS -c "$HERE/smc.c" -o "$OUT/smc.o"
$CC $FLAGS -static -no-pie -Wl,--build-id=none -T "$HERE/link.ld" -Wl,-Map,"$OUT/fpconf.map" -Wl,--no-warn-rwx-segments -o "$OUT/fpconf.elf" "$OUT/start.o" "$OUT/fpconf.o" "$OUT/ops.o" "$OUT/ops_le.o" "$OUT/benchc.o" "$OUT/bench.o" "$OUT/smc.o" -lgcc
powerpc-linux-gnu-objdump -h "$OUT/fpconf.elf" | grep -E '^ +[0-9]' || true
sha256sum "$OUT/fpconf.elf"
